// Regenerates the Lucide icon geometry the app draws (ReaderIcon). Run: node scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const icons = {
  back: 'arrow-right', chevron: 'chevron-left', check: 'check', bookmark: 'bookmark', copy: 'copy', share: 'share',
  translate: 'languages', close: 'x', trash: 'trash', restore: 'rotate-ccw', archive: 'archive', search: 'search',
  book: 'book-open', lines: 'text-align-end', word: 'whole-word', eye: 'eye', 'eye-off': 'eye-off', settings: 'settings',
  menu: 'menu', calendar: 'calendar-check', index: 'list', jump: 'locate-fixed', sun: 'sun', moon: 'moon',
  system: 'monitor-smartphone', clock: 'clock', plus: 'plus', minus: 'minus', sparkle: 'sparkles', flame: 'flame', loop: 'repeat',
  alert: 'circle-alert', info: 'info', 'chevron-down': 'chevron-down', done: 'circle-check', home: 'house', bell: 'bell', pencil: 'pencil',
};
const out = {};
for (const [name, lucide] of Object.entries(icons)) {
  // Read the data literal rather than importing the module, which needs React Native.
  const source = readFileSync(new URL(`../node_modules/lucide-react-native/dist/esm/icons/${lucide}.mjs`, import.meta.url), 'utf8');
  const literal = /const __iconData = (\{[\s\S]*?\n\});/.exec(source)?.[1];
  if (!literal) throw new Error(`Unexpected icon file: ${lucide}`);
  const __iconData = Function(`return (${literal})`)();
  out[name] = __iconData.node.map(([tag, { key: _key, ...attrs }]) => [tag, attrs]);
}
writeFileSync('src/features/quran-reader/components/ui/icon-nodes.ts', `// Generated by scripts/generate-icons.mjs from lucide-react-native (ISC). Do not edit.\n` +
  `export type IconNode = [string, Record<string, string | number>][];\n` +
  `export const iconNodes = {\n${Object.entries(out).map(([name, node]) => `  ${JSON.stringify(name)}: ${JSON.stringify(node)},`).join('\n')}\n} as const satisfies Record<string, IconNode>;\n`);
console.log(Object.keys(out).length, 'icons');
